import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = process.cwd();
const contentRoot = join(ROOT, "content");
const generatedDir = join(ROOT, "src", "content");
const output = join(generatedDir, "generated-content.ts");

function parseFrontmatter(source) {
  if (!source.startsWith("---\n")) return {};
  const end = source.indexOf("\n---", 4);
  if (end === -1) throw new Error("Missing frontmatter terminator");

  const result = {};
  for (const line of source.slice(4, end).split("\n")) {
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) continue;
    const [, key, raw] = match;
    result[key] = raw.trim().replace(/^['"]|['"]$/g, "");
  }
  return result;
}

function publicationFiles(dir, files = []) {
  if (!existsSync(dir)) return files;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) publicationFiles(full, files);
    else if (
      entry.name.endsWith(".md") &&
      entry.name !== "README.md" &&
      !entry.name.endsWith(".research.md") &&
      !entry.name.endsWith(".review.md")
    ) files.push(full);
  }
  return files;
}

const articles = publicationFiles(join(contentRoot, "blog")).map((file) => {
  const source = readFileSync(file, "utf8");
  const meta = parseFrontmatter(source);
  if (!meta.title || !meta.slug || !meta.description) {
    throw new Error(`Invalid content frontmatter: ${relative(ROOT, file)}`);
  }
  if (!meta.diagram || !meta.thesis) {
    throw new Error(`Blog article requires diagram and thesis frontmatter: ${relative(ROOT, file)}`);
  }
  return { type: "blog", sourcePath: relative(ROOT, file).replaceAll("\\", "/"), ...meta };
});

const docs = publicationFiles(join(contentRoot, "docs")).map((file) => {
  const source = readFileSync(file, "utf8");
  const meta = parseFrontmatter(source);
  if (!meta.title || !meta.slug || !meta.description) {
    throw new Error(`Invalid content frontmatter: ${relative(ROOT, file)}`);
  }
  return { type: "docs", sourcePath: relative(ROOT, file).replaceAll("\\", "/"), ...meta };
});

mkdirSync(generatedDir, { recursive: true });

const source = `// AUTO-GENERATED by scripts/generate-public-content.mjs. Do not edit manually.\n\nexport type GeneratedContentMeta = {\n  type: \"blog\" | \"docs\";\n  sourcePath: string;\n  title: string;\n  slug: string;\n  description: string;\n  category?: string;\n  diagram?: string;\n  thesis?: string;\n  primary_keyword?: string;\n  search_intent?: string;\n  author?: string;\n  published?: string;\n};\n\nexport const generatedContent = ${JSON.stringify({ articles, docs }, null, 2)} as const;\n`;

writeFileSync(output, source);
console.log(`Generated ${articles.length} blog articles and ${docs.length} docs entries.`);
